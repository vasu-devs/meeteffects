#!/usr/bin/env python3
"""Embed verified local meme assets; --check verifies offline, --download refetches.

Only individual pinned files are fetched. No image/audio conversion is performed.
See docs/MEME-SOURCES.md for provenance and the different image/audio rights.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'extension' / 'assets'
OUTPUT = ROOT / 'extension' / 'meme-assets.js'
KYM = 'https://i.kym-cdn.com/photos/images/newsfeed/'
MIRROR = ('https://raw.githubusercontent.com/GeorgeQLe/assets-sfx-combat/'
          '9662dc1bed3b06ae753045915f9accfac044c7ce/')
FILES = [
    ('memes/absolute-cinema.jpg', KYM + '002/693/282/5cb', 46486,
     '87a666f32d0f9e6f94f250983688791d1dfd1ecdcfd91d17433844db769bbdc4'),
    ('memes/im-tired-boss.jpg', KYM + '002/409/966/f17.jpg', 15633,
     'c1e549c0b102a804ae12e718940b47714c51a6cb9c31481b2b24486c7bd6cd28'),
    ('memes/this-is-fine.jpg', KYM + '001/401/347/312.jpg', 42003,
     '02ba93a4a7026ea7c6fd54a93acf832bf353bd418c97a2da40a2ba8cc484254a'),
    ('sounds/impactBell_heavy_000.ogg', MIRROR + 'assets/kenney/impact-sounds/Audio/impactBell_heavy_000.ogg', 13915,
     '94b8bb5f2d43ab65e4bcc32b28562416e9bc2c51d9fd4be1e333660ee52f977f'),
    ('sounds/impactSoft_heavy_000.ogg', MIRROR + 'assets/kenney/impact-sounds/Audio/impactSoft_heavy_000.ogg', 6570,
     '49e7ca88743fca974bb8676ea138b751cfd8f9033b5e7af8736c2a215d6edbc1'),
    ('sounds/impactWood_medium_000.ogg', MIRROR + 'assets/kenney/impact-sounds/Audio/impactWood_medium_000.ogg', 6575,
     '1723a9fd25103ed41af06054814e84e65f4a772bac86ab2dc927da93d9592ff5'),
    ('sounds/kenney-impact-sounds-license.txt', MIRROR + 'LICENSES/kenney-impact-sounds-license.txt', 608,
     'b49aa9c56b04528b95913de13e506a0f7c5e807b9925db9bfef86af1f91120db'),
]
REACTIONS = [
    ('cinema', 'Absolute cinema', 'absolute-cinema.jpg', 'impactBell_heavy_000.ogg'),
    ('tired', "I'm tired, boss", 'im-tired-boss.jpg', 'impactSoft_heavy_000.ogg'),
    ('brb', 'This is fine', 'this-is-fine.jpg', 'impactWood_medium_000.ogg'),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--download', action='store_true')
    args = parser.parse_args()
    raw = {}
    for name, url, size, digest in FILES:
        if size > 150000:
            raise ValueError(f'Individual asset exceeds budget: {name}')
        if args.download:
            request = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
            with urllib.request.urlopen(request, timeout=20) as response:
                data = response.read(size + 1)
        else:
            with (DEST / name).open('rb') as source:
                data = source.read(size + 1)
        if len(data) != size or hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f'Integrity mismatch: {name}')
        raw[name] = data

    def data_url(name, mime):
        return f'data:{mime};base64,' + base64.b64encode(raw[name]).decode('ascii')

    assets = {
        key: {'label': label,
              'image': data_url('memes/' + picture, 'image/jpeg'),
              'sound': data_url('sounds/' + sound, 'audio/ogg')}
        for key, label, picture, sound in REACTIONS
    }
    output = ('/* Embedded source images and Kenney CC0 percussion. See docs/MEME-SOURCES.md.\n'
              ' * Generated by scripts/vendor-memes.py; image/audio bytes are unmodified. */\n'
              '(() => {\n  \'use strict\';\n'
              '  (globalThis.MeetEffects ||= {}).memeAssets = '
              + json.dumps(assets, ensure_ascii=True, indent=2) + ';\n})();\n').encode('utf-8')
    raw_size = sum(len(data) for data in raw.values())
    if raw_size > 1024 * 1024 or raw_size + len(output) > 3 * 1024 * 1024:
        raise ValueError('Asset allocation exceeded')
    if args.check:
        if OUTPUT.read_bytes() != output:
            raise ValueError('Embedded bundle differs; run scripts/vendor-memes.py')
    else:
        if args.download:
            for name, data in raw.items():
                target = DEST / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
        OUTPUT.write_bytes(output)
    print(f'Verified 3 images, 3 sounds and license: {raw_size} raw bytes; '
          f'{len(output)} JS bytes; {raw_size + len(output)} combined bytes')


if __name__ == '__main__':
    main()
